import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { RELEASE_NOTES } from '../src/generated/release-notes';
import { parseMd } from '../src/shared/mini-md';

const root = path.join(__dirname, '..');

describe('the bundled release notes (generated by scripts/gen-release-notes.mjs)', () => {
  it('the committed file is what the generator writes now', () => {
    expect(() => execFileSync(process.execPath, [path.join(root, 'scripts/gen-release-notes.mjs'), '--check'], { cwd: root, stdio: 'pipe' })).not.toThrow();
  });

  it('one entry per docs/releases/v*.md, newest first, without the page title and the standard last line', () => {
    const files = fs.readdirSync(path.join(root, 'docs/releases')).filter((f) => /^v\d+\.\d+\.\d+\.md$/.test(f));
    expect(RELEASE_NOTES.map((n) => n.version).sort()).toEqual(files.map((f) => f.slice(1, -3)).sort());
    const num = (v: string) => v.split('.').map(Number);
    for (let i = 1; i < RELEASE_NOTES.length; i++) {
      const [a, b] = [num(RELEASE_NOTES[i - 1]!.version), num(RELEASE_NOTES[i]!.version)];
      expect(a[0]! - b[0]! || a[1]! - b[1]! || a[2]! - b[2]!, 'newest first').toBeGreaterThan(0);
    }
    for (const n of RELEASE_NOTES) {
      expect(n.md.length).toBeGreaterThan(100);
      expect(n.md).not.toMatch(/Updating from 0\.2\.x/);
      expect(n.md).not.toMatch(/^#{1,2} /); // (the card has its own title)
    }
  });

  it('every note renders with no marks left over (no stray ` or ** in the shown text)', () => {
    for (const n of RELEASE_NOTES) {
      const shown = parseMd(n.md).flatMap((b) => (b.kind === 'ul' ? b.items.flat() : b.inline)).map((i) => (i.style === 'code' ? '' : i.text)).join('');
      expect(shown, n.version).not.toMatch(/\*\*|`/);
    }
  });
});
