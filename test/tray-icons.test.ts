import { execFileSync } from 'node:child_process';
import path from 'node:path';
import zlib from 'node:zlib';
import { describe, expect, it } from 'vitest';
import { TRAY_ICONS } from '../src/generated/tray-icons';

const root = path.join(__dirname, '..');

/** A PNG's size and its pixels (8-bit RGBA, no interlace, every row filter 0: what the generator writes). */
function decode(b64: string): { w: number; h: number; px: Buffer } {
  const buf = Buffer.from(b64, 'base64');
  expect(buf.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a');
  let at = 8;
  let w = 0;
  let h = 0;
  const idat: Buffer[] = [];
  while (at < buf.length) {
    const len = buf.readUInt32BE(at);
    const type = buf.toString('latin1', at + 4, at + 8);
    const data = buf.subarray(at + 8, at + 8 + len);
    expect(buf.readUInt32BE(at + 8 + len), `${type} crc`).toBe(zlib.crc32(buf.subarray(at + 4, at + 8 + len)));
    if (type === 'IHDR') {
      w = data.readUInt32BE(0);
      h = data.readUInt32BE(4);
      expect([...data.subarray(8)]).toEqual([8, 6, 0, 0, 0]);
    }
    if (type === 'IDAT') idat.push(data);
    at += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));
  expect(raw.length).toBe(h * (1 + w * 4));
  const px = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) {
    expect(raw[y * (1 + w * 4)]).toBe(0);
    raw.copy(px, y * w * 4, y * (1 + w * 4) + 1, (y + 1) * (1 + w * 4));
  }
  return { w, h, px };
}

describe('the menu bar icons (generated by scripts/gen-tray-icons.mjs)', () => {
  it('the committed file is what the generator writes now', () => {
    expect(() => execFileSync(process.execPath, [path.join(root, 'scripts/gen-tray-icons.mjs'), '--check'], { cwd: root, stdio: 'pipe' })).not.toThrow();
  });

  it('four frames, each a template image at 18 px and 36 px: black with alpha only, something drawn, and every frame different', () => {
    expect(Object.keys(TRAY_ICONS).sort()).toEqual(['alert', 'idle', 'work-a', 'work-b']);
    const seen = new Set<string>();
    for (const [name, icon] of Object.entries(TRAY_ICONS)) {
      for (const [b64, size] of [[icon.x1, 18], [icon.x2, 36]] as const) {
        const { w, h, px } = decode(b64);
        expect([w, h], name).toEqual([size, size]);
        let ink = 0;
        for (let i = 0; i < px.length; i += 4) {
          expect(px[i]! | px[i + 1]! | px[i + 2]!, `${name} is black`).toBe(0);
          ink += px[i + 3]!;
        }
        expect(ink / 255, `${name} has a glyph`).toBeGreaterThan(size * 2);
        expect(ink / 255, `${name} is not a filled square`).toBeLessThan(size * size * 0.6);
        seen.add(b64);
      }
    }
    expect(seen.size).toBe(8);
  });
});
