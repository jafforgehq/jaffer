// Bundles docs/releases/v*.md into a TS module (newest version first), so the app shows its release notes with nothing new to package.
// Each note loses its page title (the card has its own) and the standard last line about updating, and ends at a `<!-- card-end -->` line when it has one. `--check` fails when the committed
// file differs (a unit test runs it).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'docs', 'releases');
const out = path.join(root, 'src', 'generated', 'release-notes.ts');

const num = (v) => v.split('.').map(Number);
const newestFirst = (a, b) => {
  const [x, y] = [num(a), num(b)];
  return y[0] - x[0] || y[1] - x[1] || y[2] - x[2];
};

/** A release note's text for the card. */
export function clean(raw) {
  const lines = raw.replace(/\r\n/g, '\n').trim().split('\n');
  const end = lines.findIndex((l) => l.trim() === '<!-- card-end -->'); // (the card shows what comes before it; GitHub shows all of it)
  if (end >= 0) lines.length = end;
  while (lines.length && /^#{1,2} /.test(lines[0])) lines.shift(); // (the page title)
  while (lines.length && (!lines[lines.length - 1].trim() || /^Updating from 0\.2\.x/.test(lines[lines.length - 1]))) lines.pop();
  return lines.join('\n').trim();
}

/** The generated file's text. */
export function releaseNotesSource() {
  const versions = fs.readdirSync(dir).map((f) => /^v(\d+\.\d+\.\d+)\.md$/.exec(f)?.[1]).filter(Boolean).sort(newestFirst);
  const notes = versions.map((version) => ({ version, md: clean(fs.readFileSync(path.join(dir, `v${version}.md`), 'utf8')) }));
  return `// GENERATED by scripts/gen-release-notes.mjs (node scripts/gen-release-notes.mjs) — do not edit. docs/releases/v*.md, newest first.\nexport const RELEASE_NOTES: { version: string; md: string }[] = ${JSON.stringify(notes, null, 2)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const body = releaseNotesSource();
  let cur = '';
  try {
    cur = fs.readFileSync(out, 'utf8');
  } catch {}
  if (process.argv.includes('--check')) {
    if (cur !== body) {
      console.error('src/generated/release-notes.ts is out of date; run: node scripts/gen-release-notes.mjs');
      process.exit(1);
    }
  } else if (cur !== body) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, body);
    console.log('wrote', path.relative(root, out));
  }
}
